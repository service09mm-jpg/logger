-- Палітра кольорів метрик стала яскравішою. Схема не змінилась — міняються
-- самі значення в уже створених рядках, інакше старі метрики так і лишились
-- би тьмяними, а форма налаштувань не змогла б показати їхній колір як
-- обраний: він більше не належить палітрі.
--
-- Кольори зіставлені за відтінком, а не за місцем у списку: синя метрика
-- лишається синьою, зелена зеленою. Єдиний виняток — коричневий, якому в
-- новій палітрі відповідника немає, тож він стає червоним.

UPDATE "Metric" SET "color" = '#3b82f6' WHERE "color" = '#4f7cac'; -- синій
UPDATE "Metric" SET "color" = '#16a34a' WHERE "color" = '#5c8a72'; -- зелений
UPDATE "Metric" SET "color" = '#d97706' WHERE "color" = '#a8734a'; -- бурштиновий
UPDATE "Metric" SET "color" = '#ec4899' WHERE "color" = '#8a5c7a'; -- рожевий
UPDATE "Metric" SET "color" = '#0891b2' WHERE "color" = '#4a7d8a'; -- бірюзовий
UPDATE "Metric" SET "color" = '#f43f5e' WHERE "color" = '#8a6f4a'; -- червоний
UPDATE "Metric" SET "color" = '#8b5cf6' WHERE "color" = '#6b6f8a'; -- фіолетовий
UPDATE "Metric" SET "color" = '#65a30d' WHERE "color" = '#7d8a4a'; -- оливковий

-- Будь-що інше (кольори, яких у жодній з палітр не було) відкидаємо на
-- типовий, щоб у базі не лишилось значень поза палітрою.
UPDATE "Metric"
SET "color" = '#3b82f6'
WHERE "color" NOT IN (
  '#3b82f6', '#d97706', '#16a34a', '#ec4899',
  '#65a30d', '#8b5cf6', '#0891b2', '#f43f5e'
);
