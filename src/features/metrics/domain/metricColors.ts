/**
 * Палітра кольорів метрик. Фіксований список, а не довільний hex, з двох причин:
 * випадковий колір легко зробити нечитабельним на темному тлі, і фіксований
 * набір тримає інтерфейс спокійним.
 *
 * Кольори не підібрані на око. Кожен має світлість у межах, де він лишається
 * читабельним і на світлому тлі, і на темному (той самий hex працює в обох
 * темах), а вся палітра перевірена на розрізнюваність при дальтонізмі:
 * найгірша сусідня пара — зелений і бурштиновий, і саме тому колір ніде не
 * лишається єдиною ознакою метрики, поряд завжди стоїть її назва.
 *
 * Порядок теж не випадковий: сусідні кольори в списку найчастіше опиняються
 * поруч на екрані, тому вони навмисно розведені за відтінком.
 *
 * Значення зберігається в `Metric.color` як рядок і підставляється прямо в CSS.
 */
export const METRIC_COLORS = [
  "#3b82f6", // синій
  "#d97706", // бурштиновий
  "#16a34a", // зелений
  "#ec4899", // рожевий
  "#65a30d", // оливковий
  "#8b5cf6", // фіолетовий
  "#0891b2", // бірюзовий
  "#f43f5e", // червоний
] as const;

export type MetricColor = (typeof METRIC_COLORS)[number];

export const DEFAULT_METRIC_COLOR: MetricColor = METRIC_COLORS[0];

/** Чи це колір з нашої палітри — перевірка для даних, що прийшли з браузера. */
export function isMetricColor(value: string): value is MetricColor {
  for (const color of METRIC_COLORS) {
    if (color === value) {
      return true;
    }
  }
  return false;
}
